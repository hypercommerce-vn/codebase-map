# VIBE-102: helpers for the content-level sections
def _has_fingerprints(result: DiffResult) -> bool:
    """True when both snapshots carry per-file content fingerprints."""
    return isinstance(result.baseline_meta.get("files"), dict) and isinstance(
        result.current_meta.get("files"), dict
    )


def _meta_without_files(meta: dict) -> dict:
    """Snapshot metadata without the per-file fingerprint table."""
    return {key: value for key, value in meta.items() if key != "files"}


def _line_range(node: Any) -> str:
    """`12-30`, or just `12` when the end line is unknown."""
    if node.line_end and node.line_end != node.line_start:
        return f"{node.line_start}-{node.line_end}"
    return str(node.line_start)


def _fmt_date(dt_str: Any) -> str:
    """Format ISO date string to short format."""
    if not dt_str:
        return "?"
    s = str(dt_str)
    if "T" in s:
        return s.split("T")[0]
    return s
